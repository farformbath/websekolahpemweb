export function getBeritaBySlug(slug) {
  if (!slug) return null;
  let decoded = slug;
  try {
    decoded = decodeURIComponent(slug);
  } catch {
    return null;
  }
  return daftarBerita.find((b) => b.slug === decoded || b.id === decoded) || null;
}
